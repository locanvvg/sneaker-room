/* =========================================================
   LỘC AN — GLOBAL CATALOG IMAGE STANDARDIZATION v6
   2026-11-01

   ONE SIZING AUTHORITY FOR THE WHOLE HOMEPAGE
   -------------------------------------------
   - IN COLLECTION + FORMERLY IN COLLECTION
   - Grid + 3D
   - desktop + mobile

   Every homepage item uses derivatives generated by:
     tools/normalize-sneaker-images.mjs

   There are NO sneaker IDs and NO per-pair sizing constants here.
   Detail/gallery pages continue to use their original source images.
========================================================= */
(() => {
  "use strict";

  const BUILD =
    "20261101-global-visual-v6";

  const ASSET_REVISION =
    "20261101-global-visual-v6";

  const NORMALIZED_PREFIX =
    "pictures/normalized/";

  const SOURCE_PREFIX =
    "pictures/source/";

  const PICTURES_PREFIX =
    "pictures/";

  const generatedMap =
    window.CATALOG_NORMALIZED_IMAGE_MAP &&
    typeof window.CATALOG_NORMALIZED_IMAGE_MAP ===
      "object"
      ? window.CATALOG_NORMALIZED_IMAGE_MAP
      : {};

  const mapHasEntries =
    Object.keys(
      generatedMap
    ).length > 0;

  function cleanPath(value) {
    return String(
      value || ""
    )
      .split("?")[0]
      .split("#")[0]
      .replace(/^\.\//, "")
      .trim();
  }

  function revisionedAsset(value) {
    const path =
      cleanPath(value);

    if (!path) {
      return "";
    }

    return (
      `${path}?asset=` +
      encodeURIComponent(
        ASSET_REVISION
      )
    );
  }

  function derivedNormalizedPath(
    value
  ) {
    const source =
      cleanPath(value);

    if (!source) {
      return "";
    }

    if (
      source.startsWith(
        NORMALIZED_PREFIX
      )
    ) {
      return source.replace(
        /\.(png|jpe?g|webp)$/i,
        ".png"
      );
    }

    if (
      source.startsWith(
        SOURCE_PREFIX
      )
    ) {
      return (
        NORMALIZED_PREFIX +
        "v6/" +
        source.slice(
          SOURCE_PREFIX.length
        )
      ).replace(
        /\.(png|jpe?g|webp)$/i,
        ".png"
      );
    }

    if (
      source.startsWith(
        PICTURES_PREFIX
      )
    ) {
      return (
        NORMALIZED_PREFIX +
        "v6/" +
        source.slice(
          PICTURES_PREFIX.length
        )
      ).replace(
        /\.(png|jpe?g|webp)$/i,
        ".png"
      );
    }

    return "";
  }

  function normalizedAssets(
    value
  ) {
    const source =
      cleanPath(value);

    if (!source) {
      return null;
    }

    const direct =
      generatedMap[source] ||
      generatedMap[
        `./${source}`
      ];

    if (
      direct &&
      typeof direct ===
        "object" &&
      !Array.isArray(direct)
    ) {
      const grid =
        cleanPath(
          direct.grid ||
          direct.view3d ||
          direct.default ||
          ""
        );

      const view3d =
        cleanPath(
          direct.view3d ||
          direct.grid ||
          direct.default ||
          ""
        );

      if (
        grid ||
        view3d
      ) {
        return {
          grid:
            grid ||
            view3d,
          view3d:
            view3d ||
            grid
        };
      }
    }

    if (
      typeof direct ===
        "string" &&
      direct
    ) {
      const normalized =
        cleanPath(
          direct
        );

      return {
        grid:
          normalized,
        view3d:
          normalized
      };
    }

    /*
      Only a temporary fallback during a manifest/cache transition.
      Normal operation uses generatedMap.
    */
    if (!mapHasEntries) {
      const derived =
        derivedNormalizedPath(
          source
        );

      if (derived) {
        return {
          grid:
            derived.replace(
              "/v6/",
              "/v6/grid/"
            ),
          view3d:
            derived
        };
      }
    }

    return null;
  }

  function originalImage(
    item
  ) {
    return cleanPath(
      item?.catalogOriginalImage ||
      item?.originalImage ||
      item?.image ||
      (
        Array.isArray(
          item?.images
        )
          ? item.images[0]
          : ""
      )
    );
  }

  function standardizeItem(
    item
  ) {
    if (
      !item ||
      typeof item !==
        "object"
    ) {
      return false;
    }

    const original =
      originalImage(
        item
      );

    if (!original) {
      return false;
    }

    const assets =
      normalizedAssets(
        original
      );

    if (
      !assets?.grid ||
      !assets?.view3d
    ) {
      /*
        Safe fallback:
        leave the source untouched until the GitHub Action generates
        its normalized derivatives.
      */
      return false;
    }

    item.catalogOriginalImage =
      original;

    item.catalogGridImage =
      revisionedAsset(
        assets.grid
      );

    item.catalog3DImage =
      revisionedAsset(
        assets.view3d
      );

    item.catalogNormalizedImage =
      true;

    item.catalogNormalizedBuild =
      BUILD;

    /*
      Grid renderers read item.image.
    */
    item.image =
      item.catalogGridImage;

    /*
      The generated bitmap now owns homepage sizing.
      Remove historical per-pair homepage calibration.
    */
    item.autoFit =
      false;

    delete item.display;

    return true;
  }

  function standardizeCollection() {
    if (
      typeof sneakers ===
        "undefined" ||
      !Array.isArray(
        sneakers
      )
    ) {
      return {
        standardized: 0,
        total: 0
      };
    }

    let standardized =
      0;

    sneakers.forEach(
      item => {
        if (
          standardizeItem(
            item
          )
        ) {
          standardized +=
            1;
        }
      }
    );

    return {
      standardized,
      total:
        sneakers.length
    };
  }

  const result =
    standardizeCollection();

  window.CatalogImageNormalization = {
    build:
      BUILD,
    assetRevision:
      ASSET_REVISION,
    standardizeCollection,
    standardizeItem,
    derivedNormalizedPath,
    normalizedAssets,
    generatedMap
  };

  console.info(
    `[Catalog Images] ${result.standardized}/${result.total} ` +
    `item(s) using global Grid + 3D normalization v6.`
  );
})();
