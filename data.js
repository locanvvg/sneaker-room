  function removeSoldBadge(card) {
    card
      .querySelectorAll(".collection-sold-badge")
      .forEach(badge => badge.remove());

    card
      .querySelectorAll(".card-edition-status")
      .forEach(wrapper => {
        const editionBadge =
          wrapper.querySelector(
            ".badge:not(.collection-sold-badge)"
          );

        const meta =
          wrapper.closest(".card-meta");

        if (editionBadge && meta) {
          meta.insertBefore(
            editionBadge,
            wrapper
          );
        }

        wrapper.remove();
      });
  }

  function addSoldBadgeBesideEdition(card) {
    /*
      GRID CARD:
      .card-meta normally contains:
      [ edition badge ] [ size ]
    */
    const meta =
      card.querySelector(".card-meta");

    if (meta) {
      let wrapper =
        meta.querySelector(".card-edition-status");

      const editionBadge =
        meta.querySelector(
          ".badge:not(.collection-sold-badge)"
        );

      if (!wrapper) {
        wrapper =
          document.createElement("span");

        wrapper.className =
          "card-edition-status";

        if (editionBadge) {
          meta.insertBefore(
            wrapper,
            editionBadge
          );

          wrapper.appendChild(
            editionBadge
          );
        } else {
          meta.insertBefore(
            wrapper,
            meta.firstChild
          );
        }
      }

      let soldBadge =
        wrapper.querySelector(
          ".collection-sold-badge"
        );

      if (!soldBadge) {
        soldBadge =
          document.createElement("span");

        soldBadge.className =
          "collection-sold-badge";

        soldBadge.textContent =
          "SOLD";

        soldBadge.setAttribute(
          "aria-label",
          "Sold"
        );

        wrapper.appendChild(
          soldBadge
        );
      }

      return;
    }

    /*
      3D card fallback:
      place SOLD beside the first edition badge if the 3D
      renderer has a comparable badge element.
    */
    const editionBadge =
      card.querySelector(
        ".badge:not(.collection-sold-badge)"
      );

    if (editionBadge) {
      let soldBadge =
        editionBadge.parentElement
          ?.querySelector(
            ".collection-sold-badge"
          );

      if (!soldBadge) {
        soldBadge =
          document.createElement("span");

        soldBadge.className =
          "collection-sold-badge";

        soldBadge.textContent =
          "SOLD";

        editionBadge.insertAdjacentElement(
          "afterend",
          soldBadge
        );
      }
    }
  }

  function decorateVisibleCards() {
    const grid =
      document.getElementById("sneaker-grid");

    if (!grid) return;

    grid
      .querySelectorAll(
        ".card, .sneaker-3d-card"
      )
      .forEach(card => {
        const sneaker =
          getRenderedSneaker(card);

        const isSold =
          statusOf(sneaker) === STATUS_SOLD;

        const archiveFit =
          Boolean(sneaker?.archiveFit);

        card.classList.toggle(
          "is-sold-card",
          isSold
        );

        card.classList.toggle(
          "archive-normalized-card",
          archiveFit
        );

        if (isSold) {
          addSoldBadgeBesideEdition(card);
        } else {
          removeSoldBadge(card);
        }
      });
  }

